#!/usr/bin/env node
/**
 * Citizen's Charter → docs/sources/citizens-charter/*.md
 *
 * Downloads each office's Citizen's Charter PDF from legazpi.gov.ph and writes a
 * plain-text Markdown transcript next to a provenance header (source URL, edition,
 * fetch date, sha256 of the PDF). Those transcripts are the SSOT the office-hub
 * JSON is derived from — nothing here writes to data/, and nothing here ships:
 * docs/ is excluded from both build paths.
 *
 * Offices marked `"extraction": "image"` in charter-sources.json have rasterized
 * page bodies, so pdftotext recovers only headers and page numbers. For those this
 * script downloads the PDF, stashes it under docs/sources/citizens-charter/pdf/,
 * and writes a placeholder transcript — the body has to be read from the page
 * images and pasted in by hand (or by an agent) before the office can be built.
 *
 * The sha256 is what makes a charter refresh detectable: if it changes, the LGU
 * republished the PDF and the derived JSON needs re-verifying.
 *
 * USAGE
 *   node scripts/data/fetch-charters.js            # all offices
 *   node scripts/data/fetch-charters.js cto hrmo   # named slugs only
 *   node scripts/data/fetch-charters.js --check    # re-hash only; report drift, write nothing
 *
 * REQUIRES `pdftotext` (poppler-utils) on PATH for text-extraction offices.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const REPO_ROOT = path.resolve(__dirname, '../..');
const MANIFEST = path.join(__dirname, 'charter-sources.json');
const OUT_DIR = path.join(REPO_ROOT, 'docs/sources/citizens-charter');
const PDF_DIR = path.join(OUT_DIR, 'pdf');

function hasPdftotext() {
  // Both poppler and xpdf builds exit non-zero for `-v` (no input file), so a
  // failed exit proves nothing — only a failure to spawn means it is missing.
  try {
    execFileSync('pdftotext', ['-v'], { stdio: 'ignore' });
    return true;
  } catch (err) {
    return err.code !== 'ENOENT';
  }
}

async function download(url) {
  const res = await fetch(url, { redirect: 'follow' });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return Buffer.from(await res.arrayBuffer());
}

function sha256(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex');
}

/** Reads the sha256 recorded in an existing transcript, or null if there isn't one. */
function recordedHash(file) {
  if (!fs.existsSync(file)) return null;
  const head = fs.readFileSync(file, 'utf8').slice(0, 2000);
  const m = head.match(/^source_sha256:\s*([0-9a-f]{64})/m);
  return m ? m[1] : null;
}

function header(office, hash) {
  return [
    '---',
    `office: ${office.office}`,
    `slug: ${office.slug}`,
    `hub: ${office.hub}`,
    `source_url: ${office.url}`,
    `source_sha256: ${hash}`,
    `extraction: ${office.extraction}`,
    `fetched: ${new Date().toISOString().slice(0, 10)}`,
    '---',
    '',
    '<!-- Generated by scripts/data/fetch-charters.js. This file is the SSOT transcript',
    "     of the published Citizen's Charter. Do not hand-edit text-extracted",
    '     transcripts; re-run the script instead. -->',
    '',
  ].join('\n');
}

const IMAGE_PLACEHOLDER = [
  '## Transcript required',
  '',
  "This charter's page bodies are rasterized images, so no text could be extracted.",
  'The PDF is saved alongside this file under `pdf/`. Read it page by page and replace',
  "this section with the transcript, preserving the charter's own field labels and",
  'table structure verbatim.',
  '',
  'Every service transcribed here still has to clear the per-service `verified` gate',
  'before the office can be built.',
  '',
].join('\n');

async function main() {
  const args = process.argv.slice(2);
  const checkOnly = args.includes('--check');
  const wanted = args.filter((a) => !a.startsWith('--'));

  const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
  const offices = wanted.length
    ? manifest.offices.filter((o) => wanted.includes(o.slug))
    : manifest.offices;

  if (!offices.length) {
    console.error(`No offices matched: ${wanted.join(', ')}`);
    process.exit(1);
  }

  const needsPdftotext = offices.some((o) => o.extraction === 'text');
  if (needsPdftotext && !checkOnly && !hasPdftotext()) {
    console.error('pdftotext not found on PATH. Install poppler-utils and retry.');
    process.exit(1);
  }

  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.mkdirSync(PDF_DIR, { recursive: true });

  let drifted = 0;

  for (const office of offices) {
    const outFile = path.join(OUT_DIR, `${office.slug}.md`);
    let pdf;
    try {
      pdf = await download(office.url);
    } catch (err) {
      console.error(`✗ ${office.slug}: ${err.message}`);
      process.exitCode = 1;
      continue;
    }

    const hash = sha256(pdf);
    const previous = recordedHash(outFile);
    const changed = previous !== null && previous !== hash;
    if (changed) drifted += 1;

    if (checkOnly) {
      const state =
        previous === null ? 'not yet fetched' : changed ? 'CHANGED upstream' : 'unchanged';
      console.log(`${changed ? '!' : ' '} ${office.slug.padEnd(6)} ${state}`);
      continue;
    }

    const pdfPath = path.join(PDF_DIR, `${office.slug}.pdf`);

    if (office.extraction === 'image') {
      fs.writeFileSync(pdfPath, pdf);
      // Never clobber a hand-written transcript on an unchanged PDF.
      if (
        previous === hash &&
        !fs.readFileSync(outFile, 'utf8').includes('## Transcript required')
      ) {
        console.log(`· ${office.slug}: transcript present and PDF unchanged, left alone`);
        continue;
      }
      fs.writeFileSync(outFile, header(office, hash) + IMAGE_PLACEHOLDER);
      console.log(`${changed ? '!' : '✓'} ${office.slug}: image PDF saved, transcript needed`);
      continue;
    }

    fs.writeFileSync(pdfPath, pdf);
    // -enc UTF-8 is not optional: without it pdftotext falls back to Latin-1 and
    // turns "Pariñas" into "Pari?as". Surnames with ñ are common here, and a
    // mangled name on a government page is a real defect, not a cosmetic one.
    const text = execFileSync('pdftotext', ['-enc', 'UTF-8', '-layout', pdfPath, '-'], {
      encoding: 'utf8',
      maxBuffer: 32 * 1024 * 1024,
    });
    fs.writeFileSync(outFile, header(office, hash) + '```\n' + text.trimEnd() + '\n```\n');
    console.log(`${changed ? '!' : '✓'} ${office.slug}: ${text.split(/\s+/).length} words`);
  }

  if (drifted) {
    console.log(
      `\n${drifted} charter(s) changed upstream — the derived JSON needs re-verifying before it ships.`
    );
    process.exitCode = checkOnly ? 1 : process.exitCode;
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
