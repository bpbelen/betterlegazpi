#!/usr/bin/env node
/**
 * Renders data/offices/*.json into the office hub pages — see ADR 0002.
 *
 * Output is written back into the *source* HTML, between sentinel comments, and
 * committed. That differs from generating only into dist/: it means the site is
 * correct when served straight from the repo (npm run dev, or a plain file server),
 * dist/ cannot drift from source, and a content change shows up as a reviewable diff
 * rather than vanishing into a build artifact. `npm run build` re-runs this first, so
 * a forgotten render cannot ship.
 *
 * Everything outside the sentinels — <head>, per-page meta and OG tags, nav, footer —
 * is left untouched, because the site has no templating layer and that chrome is
 * duplicated into every page by hand.
 *
 * Values are stored verbatim in the JSON and normalized here, never the other way
 * round, so a display rule can change without re-deriving any data:
 *   - a step with no fee shows nothing; a service with no fee at all is "Free"
 *   - totals are summed from the steps, never taken from the charter's TOTAL row
 *   - steps name positions and units; people appear only in Office Personnel
 *   - counter time is shown ahead of elapsed time (see charter-facts.js)
 *
 * USAGE
 *   node scripts/build/render-office-hubs.js                 # all offices
 *   node scripts/build/render-office-hubs.js cto             # one office
 *   node scripts/build/render-office-hubs.js --check         # fail if output is stale
 */

const fs = require('fs');
const path = require('path');
const { sumSteps, sumFees } = require('./charter-duration.js');
const { serviceFacts } = require('./charter-facts.js');

const REPO_ROOT = path.resolve(__dirname, '../..');
const OFFICES_DIR = path.join(REPO_ROOT, 'data/offices');
const START = '<!-- office-hub:start / generated by scripts/build/render-office-hubs.js -->';
const END = '<!-- office-hub:end -->';

// A plain hyphen, never an em dash. The site's copy standard bans em and en
// dashes outright, and a nothing-here placeholder does not need a wide rule.
const NOT_STATED = '<span class="hub-nil" aria-label="not stated">-</span>';

function esc(value) {
  if (value === null || value === undefined) return '';
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/** True when a fee cell means "nothing to pay" rather than an amount. */
function isFree(feeText) {
  const t = (feeText ?? '').trim();
  return !t || /^(none|n\/a|free)$/i.test(t);
}

function stepValue(value) {
  const t = (value ?? '').toString().trim();
  return t ? esc(t) : NOT_STATED;
}

const CLASSIFICATION_TONE = {
  simple: 'is-simple',
  complex: 'is-complex',
  'highly technical': 'is-technical',
};

function classificationClass(classification) {
  const key = (classification ?? '')
    .trim()
    .toLowerCase()
    .replace(/\s+transaction$/, '');
  return CLASSIFICATION_TONE[key] ?? 'is-simple';
}

/**
 * The checklist of requirements, as something you can actually tick off.
 *
 * A checkbox per row turns a read-only list into a tool for the job it is used
 * for: gathering documents at home before setting out. Ticks are stored per
 * browser by assets/js/office-hub.js. Without JavaScript these are still real
 * checkboxes and the list still reads correctly, so nothing is lost.
 */
function renderRequirements(requirements, serviceId) {
  if (!requirements?.length) return '';
  const rows = requirements
    .map((r, i) => {
      const id = `${serviceId}-req-${i}`;
      return `              <li class="hub-req">
                <input class="hub-req-box" type="checkbox" id="${esc(id)}" />
                <label class="hub-req-label" for="${esc(id)}">
                  <span class="hub-req-item">${esc(r.item)}</span>
                  ${r.whereToSecure ? `<span class="hub-req-where"><i class="bi bi-signpost-2" aria-hidden="true"></i> ${esc(r.whereToSecure)}</span>` : ''}
                </label>
              </li>`;
    })
    .join('\n');

  return `            <div class="hub-checklist" data-checklist="${esc(serviceId)}">
              <h4 class="hub-subhead">
                What to bring
                <span class="hub-checklist-count">${requirements.length} item${requirements.length === 1 ? '' : 's'}</span>
              </h4>
              <ul class="hub-reqs">
${rows}
              </ul>
            </div>`;
}

/**
 * Groups agency actions under the client step that triggers them.
 *
 * The charters number their tables exactly this way — client step 1 against agency
 * actions 1.1, 1.2, 1.3 — and a flat six-column table fights that structure: most
 * rows have no client action, so the column fills with filler text and the fee and
 * time columns fill with em dashes. Nesting removes both, and turns a table that
 * cannot reflow into a list that does.
 */
function groupSteps(steps) {
  const groups = [];
  for (const step of steps) {
    if (step.client || !groups.length) {
      groups.push({ client: step.client, actions: [] });
    }
    if (step.agency) groups[groups.length - 1].actions.push(step);
  }
  return groups;
}

function renderFact(icon, value, extraClass = '') {
  const t = (value ?? '').toString().trim();
  if (!t) return '';
  return `<span class="hub-fact ${extraClass}"><i class="bi ${icon}" aria-hidden="true"></i>${esc(t)}</span>`;
}

function renderSteps(steps) {
  if (!steps?.length) return '';

  const groups = groupSteps(steps)
    .map((group, i) => {
      const actions = group.actions
        .map((a) => {
          const facts = [
            renderFact('bi-clock', a.processingTime),
            isFree(a.feeText) ? '' : renderFact('bi-cash-coin', a.feeText, 'is-paid'),
            renderFact('bi-person-badge', a.personResponsible),
          ]
            .filter(Boolean)
            .join('');
          return `              <li class="hub-action">
                <p class="hub-action-text">${esc(a.agency)}</p>
                ${facts ? `<p class="hub-action-facts">${facts}</p>` : ''}
              </li>`;
        })
        .join('\n');

      const client = group.client
        ? `<p class="hub-step-you"><span class="hub-step-n">${i + 1}</span><span>${esc(group.client)}</span></p>`
        : '';

      return `          <li class="hub-step">
            ${client}
            ${
              group.actions.length
                ? `<p class="hub-step-label">The office then</p>
            <ol class="hub-actions">
${actions}
            </ol>`
                : ''
            }
          </li>`;
    })
    .join('\n');

  return `          <h4 class="hub-subhead">How it works</h4>
          <ol class="hub-steps">
${groups}
          </ol>`;
}

/**
 * A fee short enough for a collapsed card.
 *
 * Several CTO fees are a clause rather than an amount ("According to Order of
 * Payment Assessed, based on Ordinance No. 0013-2007"), and a chip is the wrong
 * place for a sentence: it forced the summary row 130px past a 375px viewport.
 * The full text is always shown in the body and in the totals line.
 */
function shortFee(text) {
  const t = (text ?? '').trim();
  if (t.length <= 28) return t;
  const amount = t.match(/(?:Php|P)\s?[\d,]+(?:\.\d{2})?/);
  return amount ? `From ${amount[0]}` : 'Fee applies';
}

/**
 * The strip of facts on a collapsed card.
 *
 * Ordered by the question a citizen asks first. "How long am I actually there"
 * outranks the charter's own headline figure, which is elapsed time and reads as
 * a deterrent: HRMO Recruitment is published as 29 days, but ten of those minutes
 * are yours and the rest is the office working without you.
 */
function renderSummaryFacts(svc, facts, fee) {
  const chips = [
    facts.counterUnknown
      ? ''
      : `<span class="hub-chip is-counter"><i class="bi bi-clock" aria-hidden="true"></i> ${esc(facts.counter.text)} at the counter</span>`,
    facts.sameVisit
      ? `<span class="hub-chip is-sameday"><i class="bi bi-check-circle" aria-hidden="true"></i> Done in one visit</span>`
      : facts.total.text === 'None'
        ? `<span class="hub-chip is-wait"><i class="bi bi-question-circle" aria-hidden="true"></i> Time not stated</span>`
        : `<span class="hub-chip is-wait"><i class="bi bi-calendar-event" aria-hidden="true"></i> ${esc(facts.total.text)} in total</span>`,
    facts.documents
      ? `<span class="hub-chip is-docs"><i class="bi bi-file-earmark-text" aria-hidden="true"></i> ${facts.documents} document${facts.documents === 1 ? '' : 's'}</span>`
      : '',
    `<span class="hub-chip ${fee.free ? 'is-free' : 'is-paid'}">${fee.free ? '<i class="bi bi-check-circle" aria-hidden="true"></i> Free' : `<i class="bi bi-cash-coin" aria-hidden="true"></i> ${esc(shortFee(fee.text))}`}</span>`,
  ];
  return chips.filter(Boolean).join('\n              ');
}

/**
 * The panel that answers "should I go today", before any procedural detail.
 */
function renderBeforeYouGo(svc, facts, fee) {
  const items = [
    [
      'bi-clock',
      'Your time',
      facts.sameVisit
        ? `${facts.counter.text}, and you leave with it`
        : facts.counterUnknown
          ? 'The charter does not state a processing time for this service'
          : `${facts.counter.text} at the counter, ${facts.total.text} before it is finished`,
    ],
    [
      'bi-arrow-repeat',
      'Trips to the office',
      facts.visits === 1 ? 'One visit' : `${facts.visits} separate visits`,
    ],
    facts.windows.length
      ? [
          'bi-geo-alt',
          facts.windows.length === 1 ? 'Where to go' : 'Windows used',
          facts.windows.map((w) => `Window ${w}`).join(', '),
        ]
      : ['bi-building', 'Where to go', svc.office],
    ['bi-cash-coin', 'What you pay', fee.free ? 'Nothing' : fee.text],
  ].filter(Boolean);

  return `            <div class="hub-brief">
              <h4 class="hub-brief-title">Before you go</h4>
              <dl class="hub-brief-grid">
${items
  .map(
    ([icon, label, value]) => `                <div class="hub-brief-item">
                  <dt><i class="bi ${esc(icon)}" aria-hidden="true"></i> ${esc(label)}</dt>
                  <dd>${esc(value)}</dd>
                </div>`
  )
  .join('\n')}
              </dl>
            </div>`;
}

function renderService(svc, category, aliases) {
  const fee = sumFees(svc.steps ?? []);
  const facts = serviceFacts(svc);

  const meta = [
    ['Office or division', svc.office],
    ['Who may avail', svc.whoMayAvail],
    ['Type of transaction', (svc.transactionTypes ?? []).join(', ')],
    ['Classification', svc.classification],
  ]
    .filter(([, v]) => v)
    .map(
      ([label, value]) =>
        `              <div class="hub-meta-item"><dt>${esc(label)}</dt><dd>${esc(value)}</dd></div>`
    )
    .join('\n');

  const notes = svc.notes?.length
    ? `            <aside class="hub-notes">
              <h4 class="hub-subhead">Good to know</h4>
              <ul>
${svc.notes.map((n) => `                <li>${esc(n)}</li>`).join('\n')}
              </ul>
            </aside>`
    : '';

  const draft = svc.verified
    ? ''
    : `            <p class="hub-draft" role="note"><i class="bi bi-exclamation-triangle" aria-hidden="true"></i> Draft. Not yet checked against the published charter.</p>`;

  // data-search carries the text the client-side filter matches on, so filtering
  // needs no second copy of the content and works on collapsed cards. Aliases add
  // the words people actually use ("amilyar", "cedula") which the charter never
  // prints, so searching in local terms finds the right service.
  const searchText = [
    svc.title,
    svc.description,
    svc.office,
    svc.whoMayAvail,
    ...(aliases?.[svc.id] ?? []),
  ]
    .filter(Boolean)
    .join(' ')
    .toLowerCase();

  return `      <article class="hub-service" id="${esc(svc.id)}" data-search="${esc(searchText)}"${category ? ` data-category="${esc(category)}"` : ''}>
        <details class="hub-service-shell">
          <summary class="hub-service-summary">
            <span class="hub-service-head">
              <span class="hub-service-number">${esc(svc.number)}</span>
              <span class="hub-service-title">${esc(svc.title)}</span>
            </span>
            <span class="hub-service-facts">
              ${renderSummaryFacts(svc, facts, fee)}
            </span>
          </summary>
          <div class="hub-service-body">
${draft}
            <p class="hub-service-desc">${esc(svc.description)}</p>
${renderBeforeYouGo(svc, facts, fee)}
            <dl class="hub-meta">
${meta}
            </dl>
${renderRequirements(svc.requirements, svc.id)}
${renderSteps(svc.steps)}
            <p class="hub-total">
              <span><i class="bi bi-clock" aria-hidden="true"></i> Total time <strong>${esc(facts.total.text)}</strong></span>
              <span><i class="bi bi-cash-coin" aria-hidden="true"></i> Total fee <strong>${esc(fee.free ? 'Free' : fee.text)}</strong></span>
            </p>
${notes}
          </div>
        </details>
      </article>`;
}

function renderCategories(office) {
  const byId = new Map((office.charter.services ?? []).map((s) => [s.id, s]));
  const categories = office.local?.categories ?? [];

  // With no curated categories, fall back to the charter's own grouping so a new
  // office renders sensibly before anyone has done the curation pass.
  const groups = categories.length
    ? categories.map((c) => ({ ...c, items: (c.services ?? []).map((id) => byId.get(id)) }))
    : [...new Set((office.charter.services ?? []).map((s) => s.charterGroup))].map((g) => ({
        id: String(g).toLowerCase().replace(/\W+/g, '-'),
        title: g,
        icon: null,
        items: office.charter.services.filter((s) => s.charterGroup === g),
      }));

  return groups;
}

function renderCategorySections(groups, aliases) {
  return groups
    .map(
      (
        g
      ) => `    <section class="hub-category" id="${esc(g.id)}" aria-labelledby="${esc(g.id)}-heading">
      <h3 class="hub-category-title" id="${esc(g.id)}-heading">
        ${g.icon ? `<i class="bi ${esc(g.icon)}" aria-hidden="true"></i> ` : ''}${esc(g.title)}
        <span class="hub-category-count">${g.items.filter(Boolean).length} service${g.items.filter(Boolean).length === 1 ? '' : 's'}</span>
      </h3>
${g.items
  .filter(Boolean)
  .map((svc) => renderService(svc, g.id, aliases))
  .join('\n')}
    </section>`
    )
    .join('\n');
}

/**
 * Goal-oriented entry points: "what do you need to do?"
 *
 * A citizen arrives with an errand ("I am closing my business") rather than a
 * service name, so this is the most useful navigation on the page. It sits in a
 * sticky sidebar beside the service list rather than stacked above it.
 *
 * That placement is the point. As a row of cards above the services it looked
 * identical to the category buttons below it and to the service cards below those:
 * three navigations in the same visual form, so none of them read as primary. An
 * aside beside the list is a different kind of thing, and reads as one.
 *
 * The category button row was removed when this moved: section headings already
 * mark the same divisions, and one navigation that works beats two that compete.
 */
function renderEntryPoints(office) {
  const entryPoints = office.local?.entryPoints ?? [];
  if (!entryPoints.length) return '';

  const byId = new Map((office.charter.services ?? []).map((s) => [s.id, s]));

  const items = entryPoints
    .map((ep) => {
      const services = (ep.services ?? []).map((id) => byId.get(id)).filter(Boolean);
      return `          <li class="hub-entry">
            <details class="hub-entry-shell">
              <summary class="hub-entry-summary">
                <i class="bi ${esc(ep.icon ?? 'bi-signpost-2')} hub-entry-icon" aria-hidden="true"></i>
                <span class="hub-entry-text">
                  <span class="hub-entry-title">${esc(ep.title)}</span>
                  <span class="hub-entry-count">${services.length} service${services.length === 1 ? '' : 's'}</span>
                </span>
                <i class="bi bi-chevron-down hub-entry-chevron" aria-hidden="true"></i>
              </summary>
              <ol class="hub-entry-list">
${services
  .map((svc) => `                <li><a href="#${esc(svc.id)}">${esc(svc.title)}</a></li>`)
  .join('\n')}
              </ol>
            </details>
          </li>`;
    })
    .join('\n');

  return `      <aside class="hub-journeys" aria-labelledby="hub-entrypoints-heading">
        <h3 class="hub-journeys-heading" id="hub-entrypoints-heading">
          <i class="bi bi-signpost-split" aria-hidden="true"></i>
          What do you need to do?
        </h3>
        <ul>
${items}
        </ul>
      </aside>`;
}

function renderPersonnel(office) {
  const personnel = office.charter?.personnel ?? [];
  if (!personnel.length) return '';

  // Whoever heads the office is pulled out of the roster and shown on their own.
  // Thirty-six identical cards gave the City Treasurer the same visual weight as an
  // Admin Aide, which is wrong about how the office actually works.
  const HEAD_TITLES =
    /^(city treasurer|assistant city treasurer|city (accountant|assessor|engineer|agriculturist)|cgdh|department head|officer[- ]in[- ]charge)/i;
  const head = personnel.find((p) => HEAD_TITLES.test(p.position ?? ''));
  const rest = personnel.filter((p) => p !== head);

  const units = [...new Set(rest.map((p) => p.unit ?? 'Office'))];
  const blocks = units
    .map((unit) => {
      const people = rest.filter((p) => (p.unit ?? 'Office') === unit);
      return `        <div class="hub-unit">
          <h4 class="hub-unit-title">
            ${esc(unit)}
            <span class="hub-unit-count">${people.length}</span>
          </h4>
          <ul class="hub-people">
${people.map((p) => renderPerson(p)).join('\n')}
          </ul>
        </div>`;
    })
    .join('\n');

  const notes = office.charter?.personnelNotes?.length
    ? `      <p class="hub-personnel-note"><i class="bi bi-info-circle" aria-hidden="true"></i> ${office.charter.personnelNotes.map(esc).join(' ')}</p>`
    : '';

  const headBlock = head
    ? `      <div class="hub-head">
        <span class="hub-avatar is-head" aria-hidden="true">${esc(initials(head.name))}</span>
        <span class="hub-head-text">
          <span class="hub-head-name">${esc(head.name)}</span>
          <span class="hub-head-role">${esc(head.position)}</span>
        </span>
      </div>`
    : '';

  // Thirty-six names is a lot of page to scroll past on the way to nothing, so the
  // roster collapses. The head stays visible, since that is the name most people
  // are looking for.
  return `    <section class="hub-personnel" aria-labelledby="hub-personnel-heading">
      <h3 class="hub-category-title" id="hub-personnel-heading">
        <i class="bi bi-people" aria-hidden="true"></i>
        Office personnel
        <span class="hub-category-count">${personnel.length}</span>
      </h3>
      <p class="hub-personnel-intro">Named in the Citizen's Charter. Any of the staff for a division may serve you, which is why the steps above name the division rather than an individual.</p>
${headBlock}
      <details class="hub-roster">
        <summary class="hub-roster-summary">
          <span>See all ${rest.length} staff across ${units.length} division${units.length === 1 ? '' : 's'}</span>
          <i class="bi bi-chevron-down hub-entry-chevron" aria-hidden="true"></i>
        </summary>
        <div class="hub-roster-body">
${blocks}
${notes}
        </div>
      </details>
    </section>`;
}

/** Initials for the avatar chip, at most two letters. */
function initials(name) {
  return String(name ?? '')
    .split(/\s+/)
    .filter((w) => /^[A-Za-zÑñ]/.test(w))
    .slice(0, 2)
    .map((w) => w[0].toUpperCase())
    .join('');
}

function renderPerson(p) {
  return `            <li class="hub-person">
              <span class="hub-avatar" aria-hidden="true">${esc(initials(p.name))}</span>
              <span class="hub-person-text">
                <span class="hub-person-name">${esc(p.name)}</span>
                <span class="hub-person-role">${esc(p.position)}</span>
              </span>
            </li>`;
}

function renderFeedback(office) {
  const fb = office.charter?.feedbackMechanism;
  if (!fb) return '';
  const contacts = (fb.contacts ?? [])
    .map((c) => `<li><a href="mailto:${esc(c)}">${esc(c)}</a></li>`)
    .join('');
  return `    <section class="hub-feedback" aria-labelledby="hub-feedback-heading">
      <h3 class="hub-category-title" id="hub-feedback-heading">Feedback and complaints</h3>
      ${fb.howToSendFeedback ? `<p>${esc(fb.howToSendFeedback)}</p>` : ''}
      ${fb.howFeedbackIsProcessed ? `<p>${esc(fb.howFeedbackIsProcessed)}</p>` : ''}
      ${contacts ? `<ul class="hub-contacts">${contacts}</ul>` : ''}
    </section>`;
}

/**
 * The standing disclaimer.
 *
 * Two things need saying on every hub, and both are consequences of decisions in
 * ADR 0002: the published charter is the authority, and the totals shown here are
 * summed from the steps rather than copied from the charter's TOTAL row. Where the
 * charter's own arithmetic disagrees, a reader deserves to know which number they
 * are looking at and where to check it.
 */
function renderDisclaimer(office) {
  return `    <aside class="hub-disclaimer" aria-labelledby="hub-disclaimer-heading">
      <h3 class="hub-disclaimer-title" id="hub-disclaimer-heading">
        <i class="bi bi-info-circle" aria-hidden="true"></i>
        About this information
      </h3>
      <p>
        This page reproduces the ${esc(office.charter.office)} Citizen's Charter,
        ${esc(office.charter.edition)}. The published charter is always the authority.
        If anything here differs from it, follow the charter and please tell us so we
        can correct the page.
      </p>
      <p>
        Total processing times are added up from the individual steps. Where a charter
        states a total that does not match its own steps, the figure shown here is the
        sum of the steps.
      </p>
      <p class="hub-disclaimer-actions">
        <a class="hub-btn hub-btn--primary" href="${esc(office.charter.sourceUrl)}" rel="noopener">
          <i class="bi bi-file-earmark-pdf" aria-hidden="true"></i>
          Read the official charter
        </a>
        <a class="hub-btn hub-btn--ghost" href="/contact/">
          <i class="bi bi-flag" aria-hidden="true"></i>
          Report an error
        </a>
      </p>
    </aside>`;
}

/**
 * Search across the office's services.
 *
 * Hidden until assets/js/office-hub.js runs, because a search box that does
 * nothing is worse than no search box. Everything it filters is already in the
 * page, so a reader without JavaScript loses a convenience, not any content.
 */
function renderSearch(office, serviceCount) {
  if (serviceCount < 5) return '';
  return `    <div class="hub-search" data-hub-search hidden>
      <label class="visually-hidden" for="hub-search-${esc(office.slug)}">Search ${esc(office.charter.abbreviation ?? office.charter.office)} services</label>
      <i class="bi bi-search" aria-hidden="true"></i>
      <input
        type="search"
        id="hub-search-${esc(office.slug)}"
        class="hub-search-input"
        placeholder="Search these ${serviceCount} services"
        autocomplete="off"
      />
      <p class="hub-search-status" role="status" aria-live="polite"></p>
    </div>`;
}

function renderOffice(office) {
  const partial = office.charter.partial;
  const groups = renderCategories(office);
  const serviceCount = (office.charter.services ?? []).length;

  const banner = partial
    ? `      <p class="hub-partial" role="note"><i class="bi bi-hourglass-split" aria-hidden="true"></i> ${esc(partial.transcribed)} of ${esc(partial.total)} services transcribed so far.</p>`
    : '';

  // Wrapped in the site's own section and container so the hub sits on the same
  // measure as every other page. Without this it renders edge to edge.
  return `${START}
      <section class="bpl-section">
        <div class="container">
  <div class="office-hub" data-office="${esc(office.slug)}">
    <header class="hub-header">
      <h2 class="hub-title">${esc(office.charter.office)}${office.charter.abbreviation ? ` <span class="hub-abbr">(${esc(office.charter.abbreviation)})</span>` : ''}</h2>
      <p class="hub-source">
        Citizen's Charter, ${esc(office.charter.edition)}.
        <a href="${esc(office.charter.sourceUrl)}" rel="noopener">Read the source document</a>
      </p>
${banner}
    </header>
${renderSearch(office, serviceCount)}
    <div class="hub-layout${renderEntryPoints(office) ? ' has-journeys' : ''}">
${renderEntryPoints(office)}
      <div class="hub-main">
${renderCategorySections(groups, office.local?.searchAliases)}
      </div>
    </div>
${renderPersonnel(office)}
${renderFeedback(office)}
${renderDisclaimer(office)}
  </div>
        </div>
      </section>
  ${END}`;
}

function applyToPage(office, { check }) {
  const pagePath = path.join(REPO_ROOT, office.route);
  if (!fs.existsSync(pagePath)) {
    return { status: 'missing', message: `no such page: ${office.route}` };
  }

  const html = fs.readFileSync(pagePath, 'utf8');
  const start = html.indexOf(START);
  const end = html.indexOf(END);
  if (start === -1 || end === -1) {
    return {
      status: 'no-sentinels',
      message: `${office.route} has no office-hub sentinels; add them around the content region first`,
    };
  }

  const next = html.slice(0, start) + renderOffice(office) + html.slice(end + END.length);
  if (next === html) return { status: 'unchanged' };
  if (check) return { status: 'stale' };

  fs.writeFileSync(pagePath, next);
  return { status: 'written' };
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const wanted = args.filter((a) => !a.startsWith('--'));

  const files = fs
    .readdirSync(OFFICES_DIR)
    .filter((f) => f.endsWith('.json'))
    .filter((f) => !wanted.length || wanted.includes(path.basename(f, '.json')));

  let failed = 0;
  for (const file of files) {
    const office = JSON.parse(fs.readFileSync(path.join(OFFICES_DIR, file), 'utf8'));
    const result = applyToPage(office, { check });
    const count = office.charter.services?.length ?? 0;

    if (result.status === 'written') console.log(`✓ ${office.slug}: ${count} services rendered`);
    else if (result.status === 'unchanged') console.log(`· ${office.slug}: up to date`);
    else if (result.status === 'stale') {
      console.error(`✗ ${office.slug}: rendered output is stale`);
      failed += 1;
    } else {
      console.error(`✗ ${office.slug}: ${result.message}`);
      failed += 1;
    }
  }

  if (failed) process.exit(1);
}

if (require.main === module) main();

module.exports = { renderOffice, START, END };
