#!/usr/bin/env node
/**
 * Regenerates sitemap.xml from the HTML files actually present in the repo.
 *
 * The sitemap used to be hand-maintained and drifted: at the time this script
 * was written it was missing 16 live pages (all of /policies/, /services/housing,
 * /travel/transportation and 13 office hubs under /service-details/). Generating
 * it from disk is the only way to keep that from happening again.
 *
 * Routes are emitted as clean URLs to match .htaccess and serve.py — no .html
 * extension, and <dir>/index.html collapses to <dir>/.
 *
 * Usage:
 *   node scripts/build/generate-sitemap.js          # write sitemap.xml
 *   node scripts/build/generate-sitemap.js --check  # exit 1 if out of date
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '../..');
const ORIGIN = 'https://betterlegazpi.org';
const OUT = path.join(ROOT, 'sitemap.xml');

// Directories that never contain public routes.
const EXCLUDED_DIRS = new Set([
  'node_modules',
  'dist',
  'scratch',
  'test-results',
  '.git',
  '.github',
  'admin',
  'assets',
  'data',
  'docs',
  'scripts',
  'tests',
  'references',
  'playwright-report',
]);

// Error and utility pages must not be advertised to search engines.
const EXCLUDED_FILES = new Set(['403.html', '404.html', '500.html', 'offline.html']);

/**
 * changefreq/priority by route shape. First match wins, so order matters:
 * more specific prefixes sit above the catch-alls.
 */
const RULES = [
  { test: (r) => r === '/', changefreq: 'daily', priority: '1.0' },
  { test: (r) => r === '/news/', changefreq: 'daily', priority: '0.9' },
  { test: (r) => r === '/services/', changefreq: 'weekly', priority: '0.9' },
  { test: (r) => r.startsWith('/services/'), changefreq: 'weekly', priority: '0.8' },
  { test: (r) => r.startsWith('/service-details/'), changefreq: 'monthly', priority: '0.7' },
  { test: (r) => r.startsWith('/travel/'), changefreq: 'monthly', priority: '0.7' },
  {
    test: (r) => r === '/government/' || r.startsWith('/government/'),
    changefreq: 'weekly',
    priority: '0.8',
  },
  {
    test: (r) => r === '/transparency/' || r === '/policies/',
    changefreq: 'weekly',
    priority: '0.8',
  },
  {
    test: (r) => r === '/statistics/' || r === '/contact/' || r === '/faq/',
    changefreq: 'weekly',
    priority: '0.8',
  },
  { test: (r) => r === '/about/' || r === '/history/', changefreq: 'monthly', priority: '0.7' },
  // Legal and navigational pages: real, indexable, but low priority.
  { test: () => true, changefreq: 'yearly', priority: '0.3' },
];

function walk(dir, routes = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (EXCLUDED_DIRS.has(entry.name) || entry.name.startsWith('.')) continue;
      walk(path.join(dir, entry.name), routes);
      continue;
    }
    if (!entry.name.endsWith('.html')) continue;
    if (EXCLUDED_FILES.has(entry.name)) continue;

    const abs = path.join(dir, entry.name);
    const rel = path.relative(ROOT, abs).split(path.sep).join('/');
    let route = '/' + rel;
    route = route.endsWith('/index.html')
      ? route.slice(0, -'index.html'.length)
      : route.slice(0, -'.html'.length);
    routes.push({ route, mtime: fs.statSync(abs).mtime });
  }
  return routes;
}

function rulesFor(route) {
  return RULES.find((r) => r.test(route));
}

function build() {
  const routes = walk(ROOT).sort((a, b) => a.route.localeCompare(b.route));
  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    '  <!-- Generated by scripts/build/generate-sitemap.js — do not edit by hand. -->',
  ];
  for (const { route, mtime } of routes) {
    const { changefreq, priority } = rulesFor(route);
    lines.push('  <url>');
    lines.push(`    <loc>${ORIGIN}${route}</loc>`);
    lines.push(`    <lastmod>${mtime.toISOString().slice(0, 10)}</lastmod>`);
    lines.push(`    <changefreq>${changefreq}</changefreq>`);
    lines.push(`    <priority>${priority}</priority>`);
    lines.push('  </url>');
  }
  lines.push('</urlset>', '');
  return { xml: lines.join('\n'), count: routes.length };
}

const { xml, count } = build();

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  // lastmod tracks file mtimes, which differ per checkout; compare <loc> sets only.
  const locs = (s) => (s.match(/<loc>[^<]*<\/loc>/g) || []).sort().join('\n');
  if (locs(current) !== locs(xml)) {
    console.error('sitemap.xml is out of date. Run: npm run sitemap');
    const before = new Set(locs(current).split('\n').filter(Boolean));
    const after = new Set(locs(xml).split('\n').filter(Boolean));
    for (const l of after) if (!before.has(l)) console.error('  missing: ' + l);
    for (const l of before) if (!after.has(l)) console.error('  stale:   ' + l);
    process.exit(1);
  }
  console.log(`sitemap.xml is up to date (${count} URLs).`);
} else {
  fs.writeFileSync(OUT, xml, 'utf8');
  console.log(`Wrote sitemap.xml with ${count} URLs.`);
}
